import { ContentReviewResponse } from "@/types/api";

export function exportReviewAsJson(review: ContentReviewResponse, filename = "scalezix-content-audit.json") {
  const jsonStr = JSON.stringify(review, null, 2);
  const blob = new Blob([jsonStr], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function generateMarkdownString(review: ContentReviewResponse): string {
  const lines: string[] = [];
  lines.push(`# Scalezix Content Quality & Factuality Audit Report`);
  lines.push(`*Generated: ${review.timestamp} | Model: ${review.model_used}*\n`);

  lines.push(`## Executive Scorecard`);
  lines.push(`- **Overall Content Quality Score:** ${review.summary.overall_quality_score} / 100`);
  lines.push(`- **Factuality Reliability Score:** ${review.summary.factuality_score} / 100`);
  lines.push(`- **Total Findings Flagged:** ${review.summary.total_findings}`);
  lines.push(`- **Priority Breakdown:** ${review.summary.high_priority_count} High, ${review.summary.medium_priority_count} Medium, ${review.summary.low_priority_count} Low`);
  lines.push(`- **Evidence Status:** ${review.summary.supported_claims_count} Supported | ${review.summary.contradicted_claims_count} Contradicted | ${review.summary.unverified_claims_count} Unverified\n`);

  lines.push(`### Executive Summary`);
  lines.push(`${review.summary.executive_summary}\n`);

  lines.push(`## Text Statistics & Readability`);
  lines.push(`- **Word Count:** ${review.stats.word_count} words`);
  lines.push(`- **Estimated Reading Time:** ${review.stats.reading_time_minutes} minutes`);
  lines.push(`- **Sentence Count:** ${review.stats.sentence_count} sentences (avg ${review.stats.avg_sentence_length_words} words/sentence)`);
  lines.push(`- **Flesch Reading Ease:** ${review.stats.flesch_reading_ease} / 100 (${review.stats.readability_label})`);
  lines.push(`- **Flesch-Kincaid Grade Level:** Grade ${review.stats.flesch_kincaid_grade}`);
  if (review.stats.target_keyword_occurrences > 0) {
    lines.push(`- **Target Keyword Density:** ${review.stats.target_keyword_density_percent}% (${review.stats.target_keyword_occurrences} hits)`);
  }
  lines.push("");

  lines.push(`## Detailed Findings`);
  if (!review.findings || review.findings.length === 0) {
    lines.push(`*No editorial issues detected.*`);
  } else {
    review.findings.forEach((f, idx) => {
      lines.push(`### ${idx + 1}. [${f.priority.toUpperCase()}] ${f.category}`);
      lines.push(`- **Source:** ${f.source}`);
      if (f.claim_type !== "Not Applicable") {
        lines.push(`- **Claim Type:** ${f.claim_type}`);
      }
      if (f.evidence_status !== "Not Applicable") {
        lines.push(`- **Evidence Status:** **${f.evidence_status}**`);
      }
      lines.push(`- **Excerpt:** > "${f.excerpt}"`);
      lines.push(`- **Explanation:** ${f.explanation}`);
      lines.push(`- **Suggested Action:** ${f.suggested_action}`);
      if (f.evidence_notes) {
        lines.push(`- **Evidence Notes:** *${f.evidence_notes}*`);
      }
      lines.push("");
    });
  }

  lines.push(`---\n*Report generated by Scalezix AI Content Quality & Factuality Auditor.*`);
  return lines.join("\n");
}

export function exportReviewAsMarkdown(review: ContentReviewResponse, filename = "scalezix-content-audit.md") {
  const mdStr = generateMarkdownString(review);
  const blob = new Blob([mdStr], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
